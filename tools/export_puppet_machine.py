"""Puppet Stage theme: the Essence (lottery-ball) machine of assets/Puppet/_Source/Essence Machine.psd.
Cuts every layer to its own PNG in assets/Puppet/UI/Machine/ (named by FILES below, scaled by SCALE) and writes
scripts/ui/puppet_machine.gd (PuppetMachine): where each layer goes (px from the top-left of the Bag strip) and the ball geometry.
Layer order in the game, bottom to top:
  machine_pipe_back, machine_tube_back, [every Essence], machine_box, machine_globe_glass, machine_bevel,
  machine_pipe_glass, machine_pipe_front, machine_tube_glass, machine_tube_front
Names: the PSD's "Pipe" is the horizontal tube the balls roll out of the box into (the Bag side); the PSD's "Tube" is the elbow a spell's
Essence drops into. The game's old code called them the other way round (tube = Pipe, pipe = Tube).
The PSD's pieces are not touching, so the Pipe and the Tube are slid in (PIPE_GAP) until they meet the box's body.
Glass layers are drawn at GLASS_OPACITY unless the PSD layer already has an opacity below 100% (then that is used).
Run:  python tools/export_puppet_machine.py   (needs psd-tools, numpy, pillow)"""
import os
import sys

import numpy as np
from PIL import Image
from psd_tools import PSDImage

sys.stdout.reconfigure(encoding="utf-8")
HERE = os.path.dirname(os.path.abspath(__file__))
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import asset_paths as AP
SRC = os.path.join(AP.PUPPET, "_Source", "Essence Machine.psd")
OUT = os.path.join(AP.PUPPET, "UI", "Machine")
LAYOUT = os.path.join(HERE, "..", "scripts", "ui", "puppet_machine.gd")

SCALE = 0.26  # game px per PSD px (the glass of the pipe is then 54 px: a 52 px Essence just fits)
GLASS_OPACITY = 0.6
X0 = 639.8  # game x (from the Bag strip's left) of the Pipe's left end (= where the Essence leave the Bag)
AXIS_PSD = 1253.0  # the PSD y of the Pipe's centre line ...
AXIS_Y = 45.0  # ... lands on the Bag bar's roll row (PuppetLayout.AXIS_Y)
PIPE_LEFT_PSD = 180.0
GLOBE_C_PSD = (1496.0, 645.0)  # the bowl's centre and radius (PSD px), measured on the glass layer
GLOBE_R_PSD = 270.0
SLOTS_PSD = [(0.0, -90.0), (115.0, 100.0), (-100.0, 110.0)]  # where 3 Essence rest in the bowl (offsets from its centre)
TUBE_PATH_PSD = [(2228, 960), (2228, 1100), (2189, 1199), (2090, 1245), (1990, 1255)]  # the elbow's centre line, mouth first
BOX_BODY_PSD = (1262.0, 1729.0)  # the box body's left / right edge on the pipe's row
PIPE_RIGHT_PSD = 1154.0
TUBE_LEFT_PSD = 1833.0
OVERLAP = 24.0  # PSD px the Pipe / Tube tuck over the box's body edge (about 6 game px: no gap)

psd = PSDImage.open(SRC)
layers = {g.name + "/" + l.name: l for g in psd for l in g}
assert len(layers) == 9, list(layers)

pipe_dx = 0.0
globe_dx = -((BOX_BODY_PSD[0] - PIPE_RIGHT_PSD) + OVERLAP)
box_right = BOX_BODY_PSD[1] + globe_dx
tube_dx = -((TUBE_LEFT_PSD - box_right) + OVERLAP)
GROUP_DX = {"Pipe": pipe_dx, "Globe": globe_dx, "Tube": tube_dx}


def gx(x, dx):
    return X0 + (x + dx - PIPE_LEFT_PSD) * SCALE


def gy(y):
    return AXIS_Y + (y - AXIS_PSD) * SCALE


def shrink(im):
    w, h = max(1, round(im.width * SCALE)), max(1, round(im.height * SCALE))
    return im.convert("RGBa").resize((w, h), Image.LANCZOS).convert("RGBA")


FILES = {"Pipe/Back pipe": "machine_pipe_back", "Pipe/Glass pipe": "machine_pipe_glass", "Pipe/Front pipe": "machine_pipe_front",
         "Tube/Back tube": "machine_tube_back", "Tube/Glass Tube": "machine_tube_glass", "Tube/Front tube": "machine_tube_front",
         "Globe/Box": "machine_box", "Globe/Glass Globe": "machine_globe_glass", "Globe/Bevel": "machine_bevel"}
names = {}
for key, layer in layers.items():
    group, lname = key.split("/")
    im = layer.composite().convert("RGBA")
    op = layer.opacity / 255.0
    if "glass" in lname.lower() and op >= 0.999:
        op = GLASS_OPACITY
    if op < 0.999:
        a = np.array(im)
        a[..., 3] = (a[..., 3] * op).round().astype(np.uint8)
        im = Image.fromarray(a, "RGBA")
    box = im.getchannel("A").point(lambda v: 255 if v > 4 else 0).getbbox()
    im = im.crop(box)
    x, y = layer.bbox[0] + box[0], layer.bbox[1] + box[1]
    out = FILES[key]
    small = shrink(im)
    small.save(AP.panel_path(AP.PUPPET, out))
    names[key] = (out, gx(x, GROUP_DX[group]), gy(y), small.size)
    print("  %-26s %-14s at (%.1f, %.1f)  %s" % (key, out, names[key][1], names[key][2], small.size))


def vec(x, y):
    return "Vector2(%.1f, %.1f)" % (x, y)


def pos(key):
    return vec(names[key][1], names[key][2])


def pt(x, y, dx):
    return vec(gx(x, dx), gy(y))


gc = (GLOBE_C_PSD[0] + globe_dx, GLOBE_C_PSD[1])
pipe_glass = names["Pipe/Glass pipe"]
tube_right = names["Tube/Front tube"][1] + names["Tube/Front tube"][3][0]
lines = [
    "class_name PuppetMachine",
    "extends RefCounted",
    "## GENERATED by tools/export_puppet_machine.py from Essence Machine.psd: do not edit by hand.",
    "## The Puppet Stage's Essence machine. Positions are px from the top-left of the Bag strip; the names of the pictures are in FILES of the tool.",
    "## 'Pipe' = the horizontal tube the balls roll out through (the old code's \"tube\"), 'Tube' = the elbow a spell's Essence drops into (the old \"pipe\").",
    "",
    "const PIPE_BACK := " + pos("Pipe/Back pipe"),
    "const PIPE_GLASS := " + pos("Pipe/Glass pipe"),
    "const PIPE_FRONT := " + pos("Pipe/Front pipe"),
    "const TUBE_BACK := " + pos("Tube/Back tube"),
    "const TUBE_GLASS := " + pos("Tube/Glass Tube"),
    "const TUBE_FRONT := " + pos("Tube/Front tube"),
    "const BOX := " + pos("Globe/Box"),
    "const GLOBE_GLASS := " + pos("Globe/Glass Globe"),
    "const BEVEL := " + pos("Globe/Bevel"),
    "const PIPE_X0 := %.1f  # x of the first Essence's left edge waiting in the Pipe (nearest the Bag)" % (pipe_glass[1] + 3.0),
    "const BOX_LEFT := %.1f  # the box body's left edge: an Essence right of this x is behind the box" % gx(BOX_BODY_PSD[0], globe_dx),
    "const CHUTE_X := %.1f  # centre x of the chute the Essence fall down from the globe into the box" % gx(GLOBE_C_PSD[0], globe_dx),
    "const GLOBE_C := " + vec(gx(gc[0], 0), gy(gc[1])) + "  # centre of the glass bowl (the Essence tumble round it)",
    "const GLOBE_R := %.1f  # radius of the bowl" % (GLOBE_R_PSD * SCALE),
    "const GLOBE_SLOTS := [%s]  # where 3 Essence rest in the bowl (centres)" % ", ".join(vec(gx(gc[0] + o[0], 0), gy(gc[1] + o[1])) for o in SLOTS_PSD),
    "const TUBE_PATH := [%s]  # centres: the elbow's mouth, down its leg, round the bend, out of its end (then into the box)" % ", ".join(pt(x, y, tube_dx) for x, y in TUBE_PATH_PSD),
    "const TUBE_BALL_SCALE := 0.85  # an Essence is drawn this big inside the elbow (its glass is a little narrower than the Pipe's)",
    "const TOTAL_W := %.1f  # the whole machine ends here" % tube_right,
]
with open(LAYOUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", os.path.relpath(LAYOUT, HERE))
