"""Measures the wooden alphabet in assets/Puppet/Fonts/Letters (full-size cut pictures upper_A.png / lower_a.png) and writes scripts/ui/letter_metrics.gd.
The pictures are never resized: UiSkin.letters() scales them in the game. Every glyph was drawn on its own, so each one gets a scale (file pixels -> units
where a capital letter is 1.0 tall) that evens out the drawing differences inside its class, plus a descent (how far below the baseline it hangs).
    "D:/GitHub Projects/Tachnen/.venv/Scripts/python.exe" tools/make_letter_metrics.py"""
import os
import statistics
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(ROOT, "assets", "Puppet", "Fonts", "Letters")
OUT = os.path.join(ROOT, "scripts", "ui", "letter_metrics.gd")
XH = "acemnorsuvwxz"   # lower-case letters that are x-height tall
ASC = "bdfhkl"         # tall lower-case letters (evened out to one height)
H = {}
for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ":
    H["u" + c] = Image.open(os.path.join(DIR, "upper_%s.png" % c)).height
for c in "abcdefghijklmnopqrstuvwxyz":
    H["l" + c] = Image.open(os.path.join(DIR, "lower_%s.png" % c)).height
cap = statistics.mean(H["u" + c] for c in "ABCDEFGHIJKLMNOPRSTUVWXYZ")  # (no Q: its tail hangs)
# (each picture was drawn filling its own frame, so the lower-case size can't be measured: the usual proportions are used)
xh = 0.72
asc = 1.0
S = {}
D = {}
for c in "ABCDEFGHIJKLMNOPRSTUVWXYZ":
    S["u" + c] = 1.0 / H["u" + c]
S["uQ"] = 1.0 / cap
D["uQ"] = max(0.0, H["uQ"] / cap - 1.0)
for c in XH:
    S["l" + c] = xh / H["l" + c]
for c in ASC:
    S["l" + c] = asc / H["l" + c]
# (drawn heights, in units of a capital: t and i are shorter than the tall letters; g p q y hang 0.25 below the baseline; j has the dot and a tail)
TARGET = {"t": 0.9, "i": 0.95, "j": 1.2, "g": xh + 0.25, "p": xh + 0.25, "q": xh + 0.25, "y": xh + 0.25}
for c, h in TARGET.items():
    S["l" + c] = h / H["l" + c]
    if c in "gpqyj":
        D["l" + c] = 0.25
lines = ["# Generated by tools/make_letter_metrics.py - do not edit.", "class_name LetterMetrics", "extends RefCounted",
         "## Wooden alphabet: glyph name -> [scale, descent]. scale = file px -> units where a capital is 1.0 tall; descent = units below the baseline.",
         "const X_HEIGHT := %.4f" % xh, "const GLYPHS := {"]
for k in sorted(S):
    name = ("upper_" if k[0] == "u" else "lower_") + k[1]
    lines.append('\t"%s": [%.7f, %.4f],' % (name, S[k], D.get(k, 0.0)))
lines.append("}")
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("cap px %.0f  x-height %.3f  ascender %.3f  -> %s" % (cap, xh, asc, OUT))
