"""The Bug Hunter (2026-11-12) from the user's Act2/bug hunter/bug hunter.pdf: three pieces (Bell = body + legs + the arm with the magnifying glass, Eye, Hand =
the striker arm in ONE piece) placed again in 4 frames: Idle A, Idle B, the striker lowered ("hạ chậm xuống") and raised ("nâng nhanh lên": the blow).
All three pieces share one pixel scale (0.236 page points per px), so nothing is ever resized. The Hand turns about its shoulder (the top of its ribbon, which
the PDF keeps at one point of the Bell in every frame: solved here by least squares); the Eye slides between its Idle A and Idle B place in the Bell's socket.
Output:
  assets/Puppet/Enemies/Act2/bug_hunter_rig/{bell,eye,hand}.png   the pieces, copied as they are
  assets/Puppet/Enemies/Act2/bug_hunter.png                       Idle A assembled (codex / shadow), trimmed, on a square canvas, feet on the bottom edge
  scripts/ui/bug_hunter_layout.gd                                 generated constants
Run:  python tools/export_bug_hunter_rig.py   (needs pymupdf, numpy, Pillow; then Godot --headless --editor --quit once)"""
import math
import os
import shutil

import numpy as np
import pymupdf
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ACT2 = os.path.join(HERE, "..", "assets", "Puppet", "Enemies", "Act2")
SRC = os.path.join(ACT2, "bug hunter")
OUT = os.path.join(ACT2, "bug_hunter_rig")
LAYOUT = os.path.join(HERE, "..", "scripts", "ui", "bug_hunter_layout.gd")
BY_SIZE = {(574, 736): "hand", (1479, 1680): "bell", (210, 212): "eye"}


def rot(a):
    return np.array([[math.cos(a), -math.sin(a)], [math.sin(a), math.cos(a)]])


def main():
    page = pymupdf.open(os.path.join(SRC, "bug hunter.pdf"))[0]
    by = {}
    for i in page.get_image_info(xrefs=True):
        by.setdefault(BY_SIZE[(i["width"], i["height"])], []).append(i["transform"])
    s = math.hypot(by["bell"][0][0], by["bell"][0][1]) / 1479.0  # page points per px (the same for the three pieces)
    frames = []  # (hand angle, hand origin in bell px, eye origin in bell px) for idle_a, idle_b, down, up
    for h, b, e in zip(by["hand"], by["bell"], by["eye"]):
        frames.append((math.atan2(h[1], h[0]), np.array([(h[4] - b[4]) / s, (h[5] - b[5]) / s]), np.array([(e[4] - b[4]) / s, (e[5] - b[5]) / s])))
    # the shoulder: the point of the hand picture that stays at one place of the bell in every frame
    rows, rhs = [], []
    for i in range(1, 4):
        rows.append(rot(frames[0][0]) - rot(frames[i][0]))
        rhs.append(frames[i][1] - frames[0][1])
    q = np.linalg.lstsq(np.vstack(rows), np.concatenate(rhs), rcond=None)[0]
    at = np.mean([rot(a) @ q + o for a, o, _ in frames], axis=0)
    os.makedirs(OUT, exist_ok=True)
    for n, f in (("bell", "Bell.png"), ("eye", "Eye.png"), ("hand", "Hand.png")):
        shutil.copy2(os.path.join(SRC, f), os.path.join(OUT, n + ".png"))
    with open(LAYOUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("class_name BugHunterLayout\nextends RefCounted\n## GENERATED by tools/export_bug_hunter_rig.py from Act2/bug hunter/bug hunter.pdf. Do not edit by hand.\n"
                 "## Everything in px of the Bell picture (the Hand and the Eye have the same pixel scale).\n\n")
        fh.write("const BELL := Vector2(1479, 1680)\nconst EYE_SIZE := Vector2(210, 212)\nconst HAND_SIZE := Vector2(574, 736)\n")
        fh.write("const SHOULDER := Vector2(%.2f, %.2f)  # the point of the Hand picture that turns\n" % tuple(q))
        fh.write("const SHOULDER_AT := Vector2(%.2f, %.2f)  # ... and where it sits on the Bell\n" % tuple(at))
        fh.write("const HAND_ANGLE := {\"a\": %.5f, \"b\": %.5f, \"down\": %.5f, \"up\": %.5f}  # radians, idle A / idle B / lowered / raised\n" % tuple(f[0] for f in frames))
        fh.write("const EYE_A := Vector2(%.2f, %.2f)\nconst EYE_B := Vector2(%.2f, %.2f)\n" % (*frames[0][2], *frames[1][2]))
    # Idle A assembled (full size): hand (behind) -> bell -> eye
    M = 300
    cv = Image.new("RGBA", (1479 + 2 * M, 1680 + 2 * M), (0, 0, 0, 0))
    hand = Image.open(os.path.join(OUT, "hand.png")).convert("RGBA")
    a, o, eo = frames[0]
    inv = rot(-a)  # canvas -> hand picture
    org = o + M
    m = (inv[0, 0], inv[0, 1], -(inv[0] @ org), inv[1, 0], inv[1, 1], -(inv[1] @ org))
    cv.alpha_composite(hand.transform(cv.size, Image.AFFINE, m, Image.BICUBIC))
    cv.alpha_composite(Image.open(os.path.join(OUT, "bell.png")).convert("RGBA"), (M, M))
    cv.alpha_composite(Image.open(os.path.join(OUT, "eye.png")).convert("RGBA"), (int(round(eo[0])) + M, int(round(eo[1])) + M))
    box = cv.getchannel("A").point(lambda v: 255 if v > 8 else 0).getbbox()
    cv = cv.crop(box)
    side = int(max(cv.size) * 1.08)
    sq = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    sq.alpha_composite(cv, ((side - cv.width) // 2, side - cv.height - int(side * 0.02)))
    sq.save(os.path.join(ACT2, "bug_hunter.png"))
    print("shoulder", q, "at", at, "angles(deg)", [round(math.degrees(f[0]), 1) for f in frames], "eye", frames[0][2], frames[1][2], "picture", sq.size)


if __name__ == "__main__":
    main()
